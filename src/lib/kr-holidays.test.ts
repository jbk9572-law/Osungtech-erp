import { describe, it, expect } from "vitest";
import { getHolidayName } from "./kr-holidays";

describe("getHolidayName", () => {
  // 설날/추석 연휴는 "일요일"과 겹칠 때만 대체공휴일이 생긴다(관공서의
  // 공휴일에 관한 규정 제3조) — 토요일과만 겹치는 건 해당 안 된다. 2026년
  // 추석 연휴(9/24 목 ~ 9/26 토)는 마지막 날이 토요일일 뿐 일요일과 겹치지
  // 않으므로 대체공휴일이 없다 — 예전 코드는 토/일을 구분 없이 취급해
  // 9/28을 잘못 대체공휴일로 만들었다.
  it("추석 연휴가 토요일에만 걸치면 대체공휴일이 없다 (2026)", () => {
    expect(getHolidayName("2026-09-24")).toBe("추석");
    expect(getHolidayName("2026-09-25")).toBe("추석");
    expect(getHolidayName("2026-09-26")).toBe("추석");
    expect(getHolidayName("2026-09-27")).toBeUndefined();
    expect(getHolidayName("2026-09-28")).toBeUndefined();
  });

  // 반대로 설날/추석 연휴가 일요일과 겹치면 여전히 대체공휴일이 생겨야
  // 한다 — 2024년 설날 연휴(2/9 금 ~ 2/11 일)는 실제로 2/12(월)가
  // 대체공휴일이었다.
  it("추석/설날 연휴가 일요일과 겹치면 대체공휴일이 생긴다 (2024 설날)", () => {
    expect(getHolidayName("2024-02-12")).toBe("설날 대체공휴일");
  });

  // 어린이날 같은 하루짜리 공휴일(국경일 포함)은 토요일과만 겹쳐도
  // 대체공휴일이 생겨야 한다(설날/추석과 다른 기준) — 2025년 삼일절이
  // 토요일이라 3/3(월)이 대체공휴일이었다.
  it("하루짜리 공휴일은 토요일과 겹쳐도 대체공휴일이 생긴다 (2025 삼일절)", () => {
    expect(getHolidayName("2025-03-03")).toBe("삼일절 대체공휴일");
  });
});
